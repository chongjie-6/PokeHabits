/** Effect pixels drawn like a sprite, with the top-left pixel at `[x, y]`. */
function pixelsAt(x: number, y: number, rows: string[]): Pixel[] {
  return rows.flatMap((row, dy) =>
    [...row].flatMap((key, dx): Pixel[] =>
      key === "." ? [] : [[x + dx, y + dy, key]],
    ),
  );
}

